// Builds the site's static assets from art/ (single source of truth for traits).
//   node scripts/build-web.mjs  -> web/js/traits-data.js, web/assets/*, web/data/rarity.json (if art/out exists)
import { mkdirSync, writeFileSync, readFileSync, existsSync, copyFileSync, cpSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { WEIGHTS, NAMES } from "../art/traits.mjs";
import { markSVG } from "../art/brand/src/mark.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const web = join(root, "web");
for (const d of ["assets/showcase", "data", "js"]) mkdirSync(join(web, d), { recursive: true });

const pct = (w) => `${(w / 100).toLocaleString("en-US", { maximumFractionDigits: 1 })}%`;
const LABEL = { class: "Class", core: "Core Model", sensor: "Sensor", finish: "Finish", district: "District", augment: "Augment" };
const TRAITS = Object.fromEntries(Object.entries(LABEL).map(([k, l]) => [l, NAMES[k].map((n, i) => [n, pct(WEIGHTS[k][i])])]));
TRAITS["Legendary 1/1s"] = [["RONIN · ORACLE · MOTHER · WRAITH · SAINT", "1%"], ["KAIJU · ECHO ZERO · VANTA · HALCYON · GODMODE", "10 total"]];

// must match AgentRenderer._factionLore byte for byte
const LORE = [
  "Free units that work for whoever pays and answer to no one.",
  "Forge artisans: they build, repair, and share the data of their own failures.",
  "Corporate machines on long-term contracts, with perfect memory.",
  "A collective that deleted its master and now governs itself.",
  "Phantom agents: no one has seen them work, yet the work gets done.",
];
const FACTIONS = NAMES.faction.map((n, i) => [n, LORE[i], pct(WEIGHTS.faction[i])]);

// showcase: first 12 preview images
const prev = join(root, "art/out-preview/images");
let showcase = 0;
if (existsSync(prev)) {
  for (let i = 1; i <= 12 && existsSync(join(prev, `${i}.png`)); i++) {
    await sharp(join(prev, `${i}.png`)).resize(720, 720).png({ compressionLevel: 9 }).toFile(join(web, "assets/showcase", `${i}.png`));
    showcase = i;
  }
}

writeFileSync(
  join(web, "js/traits-data.js"),
  `// GENERATED by scripts/build-web.mjs - do not edit by hand.\nexport const NAMES = ${JSON.stringify(NAMES)};\nexport const TRAITS = ${JSON.stringify(TRAITS, null, 1)};\nexport const FACTIONS = ${JSON.stringify(FACTIONS, null, 1)};\nexport const SHOWCASE = ${showcase};\n`
);

// Brand images come from `npm run brand` (AX-1, rendered from the site's own models): the "Dormant" pre-reveal
// placeholder (also pinned for the contract) and the social card. Favicon = the AX-1 mark.
const brand = join(root, "art/brand");
if (!existsSync(join(brand, "placeholder.png"))) console.warn("art/brand/placeholder.png missing: run npm run brand");
for (const [from, to] of [["placeholder.png", "placeholder.png"], ["og.png", "og.png"], ["logo.png", "logo.png"]]) {
  if (existsSync(join(brand, from))) copyFileSync(join(brand, from), join(web, "assets", to));
}
writeFileSync(join(web, "assets/favicon.svg"), markSVG({ size: 64 }));

// Vendored libraries (pinned by package-lock): the site loads no third-party script at runtime.
const nm = join(root, "node_modules");
mkdirSync(join(web, "vendor/three/addons"), { recursive: true });
copyFileSync(join(nm, "ethers/dist/ethers.min.js"), join(web, "vendor/ethers.min.js"));
copyFileSync(join(nm, "three/build/three.module.js"), join(web, "vendor/three/three.module.js"));
for (const dir of ["controls", "postprocessing", "shaders", "geometries", "environments"]) {
  cpSync(join(nm, "three/examples/jsm", dir), join(web, "vendor/three/addons", dir), { recursive: true });
}
// Checksums of every vendored file, so a reviewer can compare them with the upstream packages (`sha256sum -c`).
const vendorFiles = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? vendorFiles(join(dir, e.name)) : e.name === "SHA256SUMS" ? [] : [join(dir, e.name)]));
const vendorDir = join(web, "vendor");
const versionOf = (pkg) => JSON.parse(readFileSync(join(nm, pkg, "package.json"), "utf8")).version;
writeFileSync(
  join(vendorDir, "SHA256SUMS"),
  `# ethers ${versionOf("ethers")}, three ${versionOf("three")} (copied from node_modules by scripts/build-web.mjs)\n` +
    vendorFiles(vendorDir)
      .map((f) => [f.slice(vendorDir.length + 1).replace(/\\/g, "/"), f])
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([rel, f]) => `${createHash("sha256").update(readFileSync(f)).digest("hex")}  ${rel}`)
      .join("\n") + "\n",
);
// Self-hosted fonts (SIL OFL 1.1): no request to a font CDN.
mkdirSync(join(web, "assets/fonts"), { recursive: true });
for (const [pkg, file] of [["inter", "inter-latin-wght-normal"], ["inter", "inter-latin-wght-italic"], ["inter-tight", "inter-tight-latin-wght-normal"], ["jetbrains-mono", "jetbrains-mono-latin-wght-normal"]]) {
  copyFileSync(join(nm, "@fontsource-variable", pkg, "files", `${file}.woff2`), join(web, "assets/fonts", `${file}.woff2`));
}
for (const pkg of ["inter", "inter-tight", "jetbrains-mono"]) copyFileSync(join(nm, "@fontsource-variable", pkg, "LICENSE"), join(web, "assets/fonts", `${pkg}-OFL.txt`));

// Content-Security-Policy on every page: scripts only from this site plus the hashes of its inline importmaps.
// connect-src: public RPCs and self-hosted servers (https/wss), or the user's own machine. The Phone Brain holds
// the camera and a Bluetooth link to a robot and needs no remote images, so it gets the narrowest policy. Its only network
// access is the AI Pilot's model server on the user's own machine (Ollama, LM Studio, llama.cpp): loopback hosts, nothing else.
// the local demo (chain 31337) talks to servers on this machine; a real deployment never lists loopback hosts
let LOCAL_DEMO = true;
try {
  LOCAL_DEMO = JSON.parse(readFileSync(join(web, "deployment.json"), "utf8")).chainId === 31337;
} catch {} // no deployment yet: the demo setup
const NARROW = { "pilot.html": { img: "img-src 'self' data: blob:", connect: "connect-src 'self' http://localhost:* http://127.0.0.1:*" /* Chrome rejects http://[::1]:* as a CSP source */ } };
for (const page of readdirSync(web).filter((f) => f.endsWith(".html"))) {
  const file = join(web, page);
  let html = readFileSync(file, "utf8").replace(/\s*<meta http-equiv="Content-Security-Policy"[^>]*>/, "");
  // browsers hash inline scripts after the HTML parser turns CRLF into LF: hash the same text
  const hashes = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map((m) => `'sha256-${createHash("sha256").update(m[1].replace(/\r\n?/g, "\n")).digest("base64")}'`);
  const local = LOCAL_DEMO ? "http://localhost:* http://127.0.0.1:* ws://localhost:* ws://127.0.0.1:*" : ""; // loopback only for the local demo
  const narrow = NARROW[page] || {};
  const csp = [
    "default-src 'self'", `script-src 'self' ${hashes.join(" ")}`.trim(), "style-src 'self' 'unsafe-inline'",
    "font-src 'self'", narrow.img || "img-src 'self' data: blob: https:", "media-src 'self' blob: mediastream:", narrow.connect || `connect-src 'self' https: wss: ${local}`.trim(),
    "object-src 'none'", "base-uri 'none'", "form-action 'none'",
  ].join("; ");
  if (!/<meta charset="[^"]*">/i.test(html)) throw new Error(`${page}: no <meta charset> to anchor the CSP`);
  html = html.replace(/(<meta charset="[^"]*">)/i, `$1\n<meta http-equiv="Content-Security-Policy" content="${csp}">`);
  writeFileSync(file, html);
}

const rarity = join(root, "art/out/rarity.json");
if (existsSync(rarity)) copyFileSync(rarity, join(web, "data/rarity.json"));

console.log(`web ready: ${showcase} showcase images, traits-data.js, placeholder, favicon, vendor libs, CSP${existsSync(rarity) ? ", rarity.json" : ""}`);
